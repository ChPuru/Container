package bundle

import (
	"errors"
	"fmt"
	"path"
	"strings"

	"github.com/rahuldhali/hull/internal/oci/runtimespec"
	"github.com/rahuldhali/hull/internal/types"
)

// ExecOptions are the per-exec overrides of `docker exec`. Everything left zero
// is inherited from the container's own process spec, which is what makes
// `docker exec <ctr> env` show the container's environment rather than the
// daemon's.
type ExecOptions struct {
	// User is a --user string resolved against the container's /etc/passwd,
	// exactly as at create time. Empty inherits the container's user.
	User string
	// WorkingDir overrides the container's working directory.
	WorkingDir string
	// Env entries are merged over the container's environment, later wins.
	Env []string
	// Tty allocates a pseudo-terminal for the exec process.
	Tty bool
	// Privileged gives the exec process every capability, regardless of what
	// the container itself was started with.
	Privileged bool
	// CapAdd adds capabilities on top of the container's set. They can only be
	// added within the container's bounding set unless Privileged is set,
	// because the kernel will not let an exec exceed it.
	CapAdd []string
}

// GenerateExec builds the process block for `docker exec`, inheriting from the
// container's own spec and applying the exec's overrides.
//
// cmd is the command to run and must be non-empty. spec is the container's
// config.json as generated by Generate (or read back by Read); c supplies the
// rootfs used to resolve a --user string and the image-level defaults.
//
// A non-privileged exec cannot gain a capability the container's bounding set
// does not contain: the kernel silently drops it, so hull refuses instead of
// pretending the request worked.
func GenerateExec(c *types.Container, spec *runtimespec.Spec, cmd []string, opts ExecOptions) (*runtimespec.Process, error) {
	if c == nil {
		return nil, errors.New("bundle: nil container")
	}
	if spec == nil || spec.Process == nil {
		return nil, errors.New("bundle: the container has no process spec to inherit from")
	}
	if len(cmd) == 0 {
		return nil, fmt.Errorf("%w: docker exec needs a command to run", ErrNoCommand)
	}

	base := spec.Process

	env, err := MergeEnv(base.Env, opts.Env)
	if err != nil {
		return nil, err
	}
	if opts.Tty && !hasEnv(env, "TERM") {
		env = append(env, "TERM=xterm")
	}

	cwd := base.Cwd
	if opts.WorkingDir != "" {
		if !strings.HasPrefix(opts.WorkingDir, "/") {
			return nil, fmt.Errorf("bundle: exec working directory %q must be an absolute path", opts.WorkingDir)
		}
		cwd = path.Clean(opts.WorkingDir)
	}
	if cwd == "" {
		cwd = "/"
	}

	user := base.User
	if opts.User != "" {
		rootfs := c.RootFS
		if rootfs == "" {
			return nil, errors.New("bundle: exec --user needs the container's mounted rootfs to resolve the name")
		}
		ru, err := ResolveUser(rootfs, opts.User, c.HostConfig.GroupAdd)
		if err != nil {
			return nil, err
		}
		user = runtimespec.User{
			UID:            ru.UID,
			GID:            ru.GID,
			Umask:          u32p(0o022),
			AdditionalGids: ru.AdditionalGids,
		}
		if ru.Home != "" {
			env, err = MergeEnv(env, []string{"HOME=" + ru.Home})
			if err != nil {
				return nil, err
			}
		}
	}

	var caps []string
	switch {
	case opts.Privileged:
		caps = AllCapabilities()
	case base.Capabilities != nil:
		caps = append(caps, base.Capabilities.Bounding...)
		bounding := make(map[string]bool, len(caps))
		for _, cp := range caps {
			bounding[cp] = true
		}
		for _, add := range opts.CapAdd {
			n, err := NormalizeCapability(add)
			if err != nil {
				return nil, err
			}
			if n == "ALL" {
				return nil, errors.New("bundle: exec --cap-add ALL requires --privileged; the kernel will not let an exec exceed the container's bounding set")
			}
			if !bounding[n] {
				return nil, fmt.Errorf("bundle: exec --cap-add %s: the capability is outside the container's bounding set, so the kernel would drop it; restart the container with --cap-add %s, or use exec --privileged", n, n)
			}
		}
	default:
		for _, add := range opts.CapAdd {
			if _, err := NormalizeCapability(add); err != nil {
				return nil, err
			}
		}
	}
	proc := &runtimespec.Process{
		Terminal:        opts.Tty,
		User:            user,
		Args:            append([]string(nil), cmd...),
		Env:             env,
		Cwd:             cwd,
		Capabilities:    capsToSpec(caps),
		Rlimits:         append([]runtimespec.POSIXRlimit(nil), base.Rlimits...),
		NoNewPrivileges: base.NoNewPrivileges,
		ApparmorProfile: base.ApparmorProfile,
		OOMScoreAdj:     base.OOMScoreAdj,
	}
	if opts.Privileged {
		proc.ApparmorProfile = "unconfined"
		// An exec that is more privileged than the container must not be
		// pinned by the container's no_new_privs, or the added capabilities
		// cannot be used by a setuid helper the operator is trying to run.
		proc.NoNewPrivileges = false
	}
	return proc, nil
}
