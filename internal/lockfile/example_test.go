package lockfile_test

import (
	"fmt"
	"os"
	"path/filepath"
	"time"

	"github.com/rahuldhali/hull/internal/lockfile"
	"github.com/rahuldhali/hull/internal/types"
)

// ExampleLockfile_Save shows what hull.lock looks like in a pull request: a
// banner field standing in for the comment JSON does not have, a fixed key
// order, one entry per pinned reference and a trailing newline.
func ExampleLockfile_Save() {
	dir, err := os.MkdirTemp("", "hull-lock-example")
	if err != nil {
		panic(err)
	}
	defer os.RemoveAll(dir)
	path := filepath.Join(dir, lockfile.Filename)

	l := &lockfile.Lockfile{
		Generated: time.Date(2026, 9, 19, 12, 0, 0, 0, time.UTC),
		Platform:  "linux/amd64",
	}
	l.Add(lockfile.Entry{
		Ref:          "alpine:3.20",
		ResolvedRef:  "docker.io/library/alpine:3.20@sha256:beefc3b5b0a2d1b0fd22f7f1a1f4aed7a2b06a2f1b1b1e4c3e6f5a4b3c2d1e0f",
		Digest:       "sha256:beefc3b5b0a2d1b0fd22f7f1a1f4aed7a2b06a2f1b1b1e4c3e6f5a4b3c2d1e0f",
		ConfigDigest: "sha256:0f1e2d3c4b5a6f7e8d9c0b1a2f3e4d5c6b7a8f9e0d1c2b3a4f5e6d7c8b9a0f1e",
		Size:         1471,
		Platform:     types.Platform{OS: "linux", Architecture: "amd64"},
		Source:       "Dockerfile",
	})

	if err := l.Save(path); err != nil {
		panic(err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		panic(err)
	}
	fmt.Print(string(data))

	// Output:
	// {
	//   "_comment": "generated by hull - do not edit by hand; run 'hull lock --update'",
	//   "version": 1,
	//   "generated": "2026-09-19T12:00:00Z",
	//   "platform": "linux/amd64",
	//   "images": [
	//     {
	//       "ref": "alpine:3.20",
	//       "resolvedRef": "docker.io/library/alpine:3.20@sha256:beefc3b5b0a2d1b0fd22f7f1a1f4aed7a2b06a2f1b1b1e4c3e6f5a4b3c2d1e0f",
	//       "digest": "sha256:beefc3b5b0a2d1b0fd22f7f1a1f4aed7a2b06a2f1b1b1e4c3e6f5a4b3c2d1e0f",
	//       "configDigest": "sha256:0f1e2d3c4b5a6f7e8d9c0b1a2f3e4d5c6b7a8f9e0d1c2b3a4f5e6d7c8b9a0f1e",
	//       "size": 1471,
	//       "platform": {
	//         "architecture": "amd64",
	//         "os": "linux"
	//       },
	//       "source": "Dockerfile"
	//     }
	//   ]
	// }
}
