// Package lockfile implements hull.lock: the file that pins every image a
// project depends on to an immutable content digest, so the project rebuilds
// from byte-identical bases on any machine.
//
// A tag is a mutable pointer. "node:22" today and "node:22" in six weeks are
// two different images, and nothing in a Dockerfile or a compose file records
// which one a working build actually used. hull.lock records it: for every
// reference the project mentions, the manifest digest that reference resolved
// to, the config digest, the size, the platform and where the reference was
// found. Verify then re-resolves those references against a registry and
// reports the two ways reality can diverge from the lock: the tag has moved, or
// the locked digest is gone.
//
// The format is JSON, because the file is machine-written but reviewed by a
// human in a pull request. JSON has no comments, so the document carries a
// "_comment" field instead. Save is atomic, orders the entries deterministically
// and ends the file with a newline, so a re-lock that changes nothing produces
// no diff at all.
//
// The package is pure Go over the standard library plus internal/types,
// internal/oci/reference and internal/fsutil, so it links into the Windows CLI
// as readily as into the daemon.
package lockfile

import (
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"sort"
	"strings"
	"time"

	"github.com/ChPuru/hull/internal/fsutil"
	"github.com/ChPuru/hull/internal/oci/reference"
	"github.com/ChPuru/hull/internal/types"
)

// Conventions of the lock file itself.
const (
	// Filename is the name hull looks for in a project directory.
	Filename = "hull.lock"

	// Version is the schema version Save writes. Load accepts this version and
	// anything older; a newer file is refused rather than misread.
	Version = 1

	// CommentField is the JSON key that carries Comment. JSON has no comment
	// syntax, so the banner a reader expects at the top of a generated file is
	// an ordinary field, written first so it appears on the document's first
	// line.
	CommentField = "_comment"

	// Comment is the banner Save writes into CommentField.
	Comment = "generated by hull - do not edit by hand; run 'hull lock --update'"

	// FilePerm is the mode Save creates the lock file with. It is meant to be
	// committed, so it is world-readable.
	FilePerm fs.FileMode = 0o644

	// maxFileSize caps how much of any single project file Discover reads, so a
	// stray multi-gigabyte "Dockerfile.bak" cannot exhaust memory.
	maxFileSize = 4 << 20
)

// ErrUnsupportedVersion is returned by Load when the file on disk was written
// by a newer hull than the one reading it. Match it with errors.Is.
var ErrUnsupportedVersion = errors.New("lockfile: unsupported lock file version")

// Lockfile is a project's pinned image set.
//
// Version is the schema version, Generated the time the file was last written,
// Platform the default platform the entries were resolved for (for example
// "linux/amd64", empty when the project is platform-agnostic) and Images the
// pinned references themselves.
type Lockfile struct {
	Version   int
	Generated time.Time
	Images    []Entry
	Platform  string
}

// Entry is one pinned image reference.
//
// Ref is the reference exactly as the project writes it, for example
// "alpine:3.20". ResolvedRef is the fully qualified, digest-pinned form that
// reproduces it anywhere, for example
// "docker.io/library/alpine:3.20@sha256:...". Digest is the manifest digest the
// reference resolved to - for a multi-platform tag this is the image index
// digest, which is what re-pulls the whole multi-arch image - and ConfigDigest
// is the digest of the selected image's config blob, which is the image ID hull
// stores locally. Size is the size in bytes of the manifest content Digest
// names. Platform is the platform the entry was resolved for, Created the
// image's creation time when it is known, and Source a human-readable note of
// where the reference was found, for example "docker-compose.yml" or
// "Dockerfile".
type Entry struct {
	Ref          string
	ResolvedRef  string
	Digest       string
	ConfigDigest string
	Size         int64
	Platform     types.Platform
	Created      time.Time
	Source       string
}

// entryJSON is Entry's wire form. Every field that is commonly empty is
// omitted, so an entry carrying only a ref and a digest produces two lines of
// JSON rather than eight lines of zero values.
type entryJSON struct {
	Ref          string          `json:"ref"`
	ResolvedRef  string          `json:"resolvedRef,omitempty"`
	Digest       string          `json:"digest,omitempty"`
	ConfigDigest string          `json:"configDigest,omitempty"`
	Size         int64           `json:"size,omitempty"`
	Platform     *types.Platform `json:"platform,omitempty"`
	Created      *time.Time      `json:"created,omitempty"`
	Source       string          `json:"source,omitempty"`
}

// MarshalJSON implements json.Marshaler. It omits every empty field and emits
// times in UTC, so two locks with the same content are byte-identical whatever
// time zone they were written in.
func (e Entry) MarshalJSON() ([]byte, error) {
	out := entryJSON{
		Ref:          e.Ref,
		ResolvedRef:  e.ResolvedRef,
		Digest:       e.Digest,
		ConfigDigest: e.ConfigDigest,
		Size:         e.Size,
		Source:       e.Source,
	}
	if !platformIsZero(e.Platform) {
		p := e.Platform
		out.Platform = &p
	}
	if !e.Created.IsZero() {
		c := e.Created.UTC()
		out.Created = &c
	}
	data, err := json.Marshal(out)
	if err != nil {
		return nil, fmt.Errorf("lockfile: marshal entry %q: %w", e.Ref, err)
	}
	return data, nil
}

// UnmarshalJSON implements json.Unmarshaler, accepting the form MarshalJSON
// writes and tolerating any field being absent.
func (e *Entry) UnmarshalJSON(data []byte) error {
	var in entryJSON
	if err := json.Unmarshal(data, &in); err != nil {
		return fmt.Errorf("lockfile: parse entry: %w", err)
	}
	*e = Entry{
		Ref:          in.Ref,
		ResolvedRef:  in.ResolvedRef,
		Digest:       in.Digest,
		ConfigDigest: in.ConfigDigest,
		Size:         in.Size,
		Source:       in.Source,
	}
	if in.Platform != nil {
		e.Platform = *in.Platform
	}
	if in.Created != nil {
		e.Created = in.Created.UTC()
	}
	return nil
}

// document is the top-level wire form, with the comment banner first.
type document struct {
	Comment   string    `json:"_comment"`
	Version   int       `json:"version"`
	Generated time.Time `json:"generated"`
	Platform  string    `json:"platform,omitempty"`
	Images    []Entry   `json:"images"`
}

// Load reads the lock file at path.
//
// A missing or empty file is not an error: Load returns an empty lock file at
// the current schema version, so a caller can Load, Add and Save without a
// special case for the first run. A file that exists but cannot be read or
// parsed is an error, as is one written by a newer schema version, which is
// reported as ErrUnsupportedVersion rather than silently half-understood.
func Load(path string) (*Lockfile, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return &Lockfile{Version: Version}, nil
		}
		return nil, fmt.Errorf("lockfile: read %s: %w", path, err)
	}
	if strings.TrimSpace(string(data)) == "" {
		return &Lockfile{Version: Version}, nil
	}

	var doc document
	if err := json.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("lockfile: parse %s: %w", path, err)
	}
	if doc.Version > Version {
		return nil, fmt.Errorf("%w: %s is version %d, this hull understands up to %d",
			ErrUnsupportedVersion, path, doc.Version, Version)
	}
	if doc.Version == 0 {
		doc.Version = Version
	}
	return &Lockfile{
		Version:   doc.Version,
		Generated: doc.Generated.UTC(),
		Images:    doc.Images,
		Platform:  doc.Platform,
	}, nil
}

// Save writes the lock file to path atomically.
//
// The entries are sorted by canonical reference, then platform, then digest, so
// the order on disk depends only on the content and never on the order things
// were added. The document is indented with two spaces, its keys are in a fixed
// order, and the file ends with a newline: all so that it reads well and diffs
// cleanly in a pull request.
//
// Save fills in a zero Version, and a zero Generated with the current time, but
// it never rewrites a Generated that is already set. Re-saving an unchanged
// lock file therefore reproduces it byte for byte.
func (l *Lockfile) Save(path string) error {
	if l.Version == 0 {
		l.Version = Version
	}
	if l.Generated.IsZero() {
		l.Generated = time.Now().UTC().Truncate(time.Second)
	}
	l.sortImages()

	images := l.Images
	if images == nil {
		images = []Entry{}
	}
	doc := document{
		Comment:   Comment,
		Version:   l.Version,
		Generated: l.Generated.UTC(),
		Platform:  l.Platform,
		Images:    images,
	}
	data, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return fmt.Errorf("lockfile: marshal %s: %w", path, err)
	}
	data = append(data, '\n')
	if err := fsutil.WriteFileAtomic(path, data, FilePerm); err != nil {
		return fmt.Errorf("lockfile: write %s: %w", path, err)
	}
	return nil
}

// Add records e, replacing any existing entry for the same reference and
// platform. References are compared in canonical form, so adding
// "docker.io/library/alpine:3.20" updates an entry stored as "alpine:3.20"
// rather than duplicating it.
func (l *Lockfile) Add(e Entry) {
	key := entryKey(e.Ref, e.Platform)
	for i := range l.Images {
		if entryKey(l.Images[i].Ref, l.Images[i].Platform) == key {
			l.Images[i] = e
			return
		}
	}
	l.Images = append(l.Images, e)
}

// Lookup returns the entry pinning ref, comparing references in canonical form
// so that "alpine", "alpine:latest" and "docker.io/library/alpine:latest" all
// find the same entry. When several platforms are locked for one reference, the
// first in the file's sorted order is returned.
func (l *Lockfile) Lookup(ref string) (Entry, bool) {
	want := canonical(ref)
	best := -1
	for i := range l.Images {
		if canonical(l.Images[i].Ref) != want {
			continue
		}
		if best < 0 || entryKey(l.Images[i].Ref, l.Images[i].Platform) < entryKey(l.Images[best].Ref, l.Images[best].Platform) {
			best = i
		}
	}
	if best < 0 {
		return Entry{}, false
	}
	return l.Images[best], true
}

// Remove deletes every entry whose reference canonicalises to ref, and reports
// whether anything was removed.
func (l *Lockfile) Remove(ref string) bool {
	want := canonical(ref)
	kept := l.Images[:0]
	removed := false
	for _, e := range l.Images {
		if canonical(e.Ref) == want {
			removed = true
			continue
		}
		kept = append(kept, e)
	}
	l.Images = kept
	return removed
}

// sortImages puts the entries into the canonical on-disk order.
func (l *Lockfile) sortImages() {
	sort.SliceStable(l.Images, func(i, j int) bool {
		a, b := l.Images[i], l.Images[j]
		ka, kb := entryKey(a.Ref, a.Platform), entryKey(b.Ref, b.Platform)
		if ka != kb {
			return ka < kb
		}
		return a.Digest < b.Digest
	})
}

// entryKey is the identity of an entry: canonical reference plus platform.
func entryKey(ref string, plat types.Platform) string {
	return canonical(ref) + "\x00" + FormatPlatform(plat)
}

// canonical normalises a reference for comparison. A reference that does not
// parse is compared by its trimmed literal text, so unparseable input still
// de-duplicates against itself instead of collapsing into one bucket.
func canonical(ref string) string {
	r, err := reference.Parse(ref)
	if err != nil {
		return strings.TrimSpace(ref)
	}
	return r.String()
}

// platformIsZero reports whether p carries no information. types.Platform holds
// a slice, so it cannot be compared with ==.
func platformIsZero(p types.Platform) bool {
	return p.OS == "" && p.Architecture == "" && p.Variant == "" &&
		p.OSVersion == "" && len(p.OSFeatures) == 0
}

// FormatPlatform renders a platform as os/arch or os/arch/variant, and as the
// empty string for the zero platform. It is the spelling used in the lock
// file's Platform field and in hull's --platform flag.
func FormatPlatform(p types.Platform) string {
	if p.OS == "" && p.Architecture == "" {
		return ""
	}
	parts := make([]string, 0, 3)
	parts = append(parts, p.OS, p.Architecture)
	if p.Variant != "" {
		parts = append(parts, p.Variant)
	}
	return strings.Join(parts, "/")
}

// ParsePlatform parses os/arch or os/arch/variant, the spelling docker's
// --platform flag uses. An empty string yields the zero platform and no error,
// which callers read as "whatever the host is".
func ParsePlatform(s string) (types.Platform, error) {
	s = strings.TrimSpace(s)
	if s == "" {
		return types.Platform{}, nil
	}
	parts := strings.Split(s, "/")
	for _, p := range parts {
		if p == "" {
			return types.Platform{}, fmt.Errorf("lockfile: platform %q has an empty component, want os/arch[/variant]", s)
		}
	}
	switch len(parts) {
	case 2:
		return types.Platform{OS: parts[0], Architecture: parts[1]}, nil
	case 3:
		return types.Platform{OS: parts[0], Architecture: parts[1], Variant: parts[2]}, nil
	default:
		return types.Platform{}, fmt.Errorf("lockfile: platform %q has %d components, want os/arch[/variant]", s, len(parts))
	}
}
